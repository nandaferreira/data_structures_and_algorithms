/*Defina uma lista encadeada


A lista encadeada é uma maneira de representar oobjetos em sequência na memória, de maneira dinâmica, uma vez que cada 
elemento é alocado por demanda e possui um ponteiro para o próximo elemento da lista. Com isso, é possível ter acesso à qualquer elemento
disponível na lista sem que esse acesso seja, obrigatoriamente, sequencial.*/